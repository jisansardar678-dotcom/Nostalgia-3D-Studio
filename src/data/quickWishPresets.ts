const mapWords = (words: { word: string; color: string }[], prefix: string): WordItem[] => {
  return words.map((item, idx) => ({
    id: `${prefix}_${idx + 1}`,
    text: item.word,
    color: item.color,
    size: idx % 4 === 0 ? 'large' : idx % 3 === 0 ? 'medium' : 'small',
  }));
};

